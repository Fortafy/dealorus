/**
 * Get the description for an NTEE code from CharityAPI via backend
 * @param {string} code - The NTEE code (e.g., "A03")
 * @returns {Promise<string|null>} - The description or null if not found
 */
export async function getNTEEDescription(code) {
  if (!code) return null;
  
  const upperCode = code.toUpperCase().trim();
  
  try {
    // Use backend function to lookup NTEE code via CharityAPI
    const { base44 } = await import('@/api/base44Client');
    const response = await base44.functions.invoke('lookupNTEECode', { code: upperCode });
    
    if (response.data?.description) {
      return response.data.description;
    }
  } catch (err) {
    console.warn(`CharityAPI lookup failed for ${upperCode}, falling back to local lookup:`, err);
  }
  
  // Fall back to local lookup
  if (NTEE_CODES[upperCode]) {
    return NTEE_CODES[upperCode];
  }
  
  // Try category letter only (e.g., "A" from "A03")
  const categoryLetter = upperCode.charAt(0);
  if (NTEE_CODES[categoryLetter]) {
    return NTEE_CODES[upperCode] || NTEE_CODES[categoryLetter];
  }
  
  return null;
}

/**
 * Search NTEE codes by description (case-insensitive, partial match)
 * @param {string} searchTerm - The search term
 * @returns {Array<{code: string, description: string}>} - Array of matching codes
 */
export function searchNTEECodes(searchTerm) {
  if (!searchTerm) return [];
  
  const lowerSearch = searchTerm.toLowerCase();
  const results = [];
  
  for (const [code, description] of Object.entries(NTEE_CODES)) {
    if (description.toLowerCase().includes(lowerSearch)) {
      results.push({ code, description });
    }
  }
  
  return results;
}

/**
 * Get all NTEE codes in a category
 * @param {string} categoryLetter - The category letter (e.g., "A")
 * @returns {Array<{code: string, description: string}>} - Array of codes in category
 */
export function getNTEECategory(categoryLetter) {
  if (!categoryLetter) return [];
  
  const upperLetter = categoryLetter.toUpperCase().charAt(0);
  const results = [];
  
  for (const [code, description] of Object.entries(NTEE_CODES)) {
    if (code.startsWith(upperLetter)) {
      results.push({ code, description });
    }
  }
  
  return results;
}